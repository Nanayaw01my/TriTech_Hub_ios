/**
 * Builds the Windows script for computer (USB) enrollment — used on new phones
 * where Google Play Protect blocks QR setup. The script:
 *   1. downloads Google's Android platform-tools (adb) once,
 *   2. downloads the latest lock app from this server,
 *   3. waits for a phone with USB debugging allowed,
 *   4. installs the app, makes it Device Owner, and sends it the stock
 *      enrollment details (same as the QR), so it appears in Enroll Stock.
 */
function buildEnrollScript({ token, backend, apkUrl }) {
  const PKG = 'com.dandorsolar.lockagent';
  const lines = [
    '@echo off',
    'setlocal',
    'title Dan and Dor Solar - Enroll phone with computer',
    'color 0F',
    `set "TOKEN=${token}"`,
    `set "BACKEND=${backend}"`,
    `set "APKURL=${apkUrl}"`,
    `set "PKG=${PKG}"`,
    'set "TOOLS=%USERPROFILE%\\DanDorSolar"',
    'set "ADB=%TOOLS%\\platform-tools\\adb.exe"',
    'set "APK=%TOOLS%\\dandorsolar-lock-agent.apk"',
    'if not exist "%TOOLS%" mkdir "%TOOLS%"',
    '',
    'echo ============================================================',
    'echo   Dan and Dor Solar - enroll a phone with this computer',
    'echo ============================================================',
    'echo.',
    '',
    'if exist "%ADB%" goto have_adb',
    'echo Downloading Android tools from Google - one time only...',
    'powershell -NoProfile -ExecutionPolicy Bypass -Command "$ProgressPreference=\'SilentlyContinue\'; [Net.ServicePointManager]::SecurityProtocol=\'Tls12\'; Invoke-WebRequest -UseBasicParsing \'https://dl.google.com/android/repository/platform-tools-latest-windows.zip\' -OutFile \'%TOOLS%\\pt.zip\'; Expand-Archive -Force \'%TOOLS%\\pt.zip\' \'%TOOLS%\'"',
    'if exist "%ADB%" goto have_adb',
    'echo.',
    'echo Could not download the Android tools. Check the internet connection and run this file again.',
    'goto fail',
    '',
    ':have_adb',
    'echo Downloading the latest lock app...',
    'if exist "%APK%" del /q "%APK%"',
    'powershell -NoProfile -ExecutionPolicy Bypass -Command "$ProgressPreference=\'SilentlyContinue\'; [Net.ServicePointManager]::SecurityProtocol=\'Tls12\'; Invoke-WebRequest -UseBasicParsing \'%APKURL%\' -OutFile \'%APK%\'"',
    'if exist "%APK%" goto have_apk',
    'echo.',
    'echo Could not download the lock app from %APKURL%. Check the internet and try again.',
    'goto fail',
    '',
    ':have_apk',
    '"%ADB%" start-server >nul 2>&1',
    'echo.',
    'echo Connect the phone with a USB cable.',
    'echo On the phone, tap ALLOW on "Allow USB debugging?" - tick "Always allow".',
    'echo Waiting for the phone...',
    ':wait_phone',
    '"%ADB%" get-state 2>nul | find "device" >nul',
    'if not errorlevel 1 goto phone_ok',
    'timeout /t 2 /nobreak >nul',
    'goto wait_phone',
    '',
    ':phone_ok',
    'for /f "delims=" %%m in (\'"%ADB%" shell getprop ro.product.model\') do set "MODEL=%%m"',
    'echo Phone found: %MODEL%',
    'echo.',
    'echo Installing the lock app...',
    '"%ADB%" install -r "%APK%" > "%TOOLS%\\install.txt" 2>&1',
    'type "%TOOLS%\\install.txt"',
    'find /i "Success" "%TOOLS%\\install.txt" >nul',
    'if not errorlevel 1 goto installed',
    'echo.',
    'echo INSTALL FAILED. Make sure Google Play Protect is OFF on the phone',
    'echo (Settings - Security - Google Play Protect) and, in Developer options,',
    'echo "Verify apps over USB" is OFF. Then run this file again.',
    'goto fail',
    '',
    ':installed',
    'echo.',
    'echo Making the lock app the phone manager - Device Owner...',
    '"%ADB%" shell dpm set-device-owner %PKG%/.LockDeviceAdminReceiver > "%TOOLS%\\dpm.txt" 2>&1',
    'type "%TOOLS%\\dpm.txt"',
    'find /i "Success" "%TOOLS%\\dpm.txt" >nul',
    'if not errorlevel 1 goto owner_ok',
    'find /i "already" "%TOOLS%\\dpm.txt" >nul',
    'if not errorlevel 1 goto owner_ok',
    'echo.',
    'echo COULD NOT MAKE IT THE PHONE MANAGER.',
    'echo The phone must have NO accounts on it - no Google, Samsung, Transsion or other account.',
    'echo Fix: factory reset the phone, and during setup SKIP every sign-in.',
    'echo Then turn on USB debugging again and run this file again.',
    'goto fail',
    '',
    ':owner_ok',
    'echo.',
    'echo Linking the phone to your stock...',
    '"%ADB%" shell am broadcast --include-stopped-packages -n %PKG%/.AdbProvisionReceiver --es enrollment_token %TOKEN% --es backend_url %BACKEND% > "%TOOLS%\\link.txt" 2>&1',
    'type "%TOOLS%\\link.txt"',
    'find /i "enroll: ok" "%TOOLS%\\link.txt" >nul',
    'if not errorlevel 1 goto done',
    'find /i "already enrolled" "%TOOLS%\\link.txt" >nul',
    'if not errorlevel 1 goto done',
    'echo.',
    'echo The app is installed but could not reach the server yet.',
    'echo Make sure the phone is connected to Wi-Fi with internet, then run this file again.',
    'goto fail',
    '',
    ':done',
    'echo.',
    'echo ============================================================',
    'echo   DONE. %MODEL% is enrolled.',
    'echo   It now shows "Awaiting Activation" and appears in Enroll Stock.',
    'echo   USB debugging is switched off automatically.',
    'echo   Unplug the phone. To enroll the next phone, run this file again.',
    'echo ============================================================',
    'pause',
    'exit /b 0',
    '',
    ':fail',
    'echo.',
    'pause',
    'exit /b 1',
    '',
  ];
  return lines.join('\r\n');
}

module.exports = { buildEnrollScript };
